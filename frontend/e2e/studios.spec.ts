import {test,expect} from '@playwright/test';
test('rule governance and sourced selection/pricing foundations stay unverified',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'Enter local demo as Alice (engineer)',exact:true}).click();
 await page.getByRole('button',{name:'Go to Standards Registry',exact:true}).click();
 await page.getByRole('button',{name:'Engineering rules',exact:true}).click();
 const criterion='PART_'+Date.now();
 await page.getByLabel('Criterion ID',{exact:true}).fill(criterion);
 await page.getByLabel('Rule name',{exact:true}).fill('Synthetic part evidence check');
 await page.getByRole('combobox',{name:'Equipment category',exact:true}).selectOption('Spare Parts');
 await page.getByRole('combobox',{name:'Input parameter',exact:true}).selectOption('part_number');
 await page.getByLabel('Rule source and authority',{exact:true}).fill('Synthetic E2E evidence policy only');
 await page.getByRole('button',{name:'Submit draft — no automatic approval',exact:true}).click();
 const row=page.locator('.rule-record').filter({hasText:criterion});await expect(row).toContainText('DRAFT');
 await row.locator('summary').click();
 await page.getByLabel('Reason for selected synthetic-rule approval',{exact:true}).fill('Approved for isolated synthetic demonstration only');
 await row.getByRole('button',{name:'Approve this synthetic version',exact:true}).click();
 await expect(row).toContainText('APPROVED');
 await page.getByRole('button',{name:'Go to Product Library',exact:true}).click();
 const family='Synthetic family '+Date.now();
 await page.getByLabel('Family name',{exact:true}).fill(family);
 await page.getByLabel('Source reference',{exact:true}).fill('Synthetic datasheet for reference only');
 await page.getByLabel('Source revision',{exact:true}).fill('A');
 await page.getByRole('button',{name:'Save product family reference',exact:true}).click();
 await expect(page.getByRole('heading',{name:family,exact:true})).toBeVisible();
 const session=await (await page.request.get('/api/v1/session')).json();
 const name='Studio source '+Date.now();
 const response=await page.request.post('/api/v1/rfqs',{headers:{'X-CSRF-Token':session.csrf},data:{name,classification:{product_category:'Pump / Pump Set',market_area:'Water',application:'Water Supply',customer:'Synthetic customer'},equipment:[{tag:'P-101',product_category:'Pump / Pump Set'}]}});
 expect(response.status()).toBe(201);
 await page.getByRole('button',{name:'Go to Dashboard',exact:true}).click();
 await page.getByRole('button',{name,exact:true}).click();
 await page.getByRole('button',{name:'Selection Studio',exact:true}).click();
 await page.getByRole('combobox',{name:'Product family',exact:true}).selectOption({label:family+' · UNVERIFIED'});
 await page.getByLabel('Evidence reference',{exact:true}).fill('Synthetic manual candidate reference');
 await page.getByLabel('Engineer notes',{exact:true}).fill('Review reference only; no performance validation');
 await page.getByRole('button',{name:'Save unverified candidate reference',exact:true}).click();
 await expect(page.getByRole('heading',{name:family,exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Record reference review using engineer notes',exact:true}).click();
 await expect(page.getByText('REFERENCE_REVIEWED · alice: Review reference only; no performance validation',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Pricing Studio',exact:true}).click();
 await page.getByLabel('Manually supplied amount (optional)',{exact:true}).fill('1200');
 await page.getByLabel('Valid until',{exact:true}).fill('2030-01-01');
 await page.getByLabel('Price source',{exact:true}).fill('Synthetic source for E2E only');
 await page.getByLabel('Source revision',{exact:true}).fill('A');
 await page.getByRole('button',{name:'Store draft price reference',exact:true}).click();
 await expect(page.getByText(/DRAFT_UNAPPROVED/)).toBeVisible();
 await page.getByRole('button',{name:'Quotation Studio',exact:true}).click();
 await expect(page.getByRole('button',{name:'Create preliminary quotation draft',exact:true})).toBeDisabled();
 expect(await page.getByRole('alert').count()).toBe(0);
});
